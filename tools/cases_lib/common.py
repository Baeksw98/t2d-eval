def norm_alias(s):
    """Alias matching ignores case, spaces, hyphens and underscores: 'GPT 6.1 Sol' = 'GPT6.1 Sol' = 'gpt-6.1-sol'."""
    return re.sub(r'[\s_\-]+', '', str(s or '').lower())


class Models:
    def __init__(self, entries):
        self.entries = entries            # [{code, name, aliases}]
        self.by_code = {m['code']: m for m in entries}
        self.alias = {}
        for m in entries:
            for a in [m['code'], m.get('name', '')] + list(m.get('aliases') or []):
                if a:
                    self.alias[norm_alias(a)] = m['code']

    def code_of(self, text):
        return self.alias.get(norm_alias(text))

    def name_of(self, code):
        m = self.by_code.get(code)
        return (m.get('name') or code) if m else code


def load_models(problems, path=None):
    path = pathlib.Path(path or (CASES / 'models.json'))
    d = load_json(path, problems)
    if d is None:
        return Models([])
    entries = d.get('models') if isinstance(d, dict) else None
    where = rel(path)
    if not isinstance(entries, list) or not entries:
        problems.error(where, '"models" 목록이 없습니다 [models-empty]', '예: {"models": [{"code": "gpt", "name": "…", "aliases": ["…"]}]}')
        return Models([])
    seen_code, seen_alias, good = {}, {}, []
    for i, m in enumerate(entries):
        w = '%s models[%d]' % (where, i)
        code = m.get('code') if isinstance(m, dict) else None
        if not isinstance(code, str) or not re.match(r'^[a-z][a-z0-9]{0,23}$', code):
            problems.error(w, 'code 는 영문 소문자로 시작하는 짧은 이름이어야 합니다 (예: gpt, claude) — 받은 값 %r [bad-model-code]' % (code,),
                           'code 는 unit 키(P051_gpt)와 응답 시트의 Model 열에 쓰이므로 밑줄(_)·대문자·공백을 쓰지 마세요')
            continue
        if code in seen_code:
            problems.error(w, '모델 code "%s" 가 두 번 있습니다 [duplicate-model]' % code)
            continue
        seen_code[code] = 1
        for a in [code, m.get('name', '')] + list(m.get('aliases') or []):
            if not a:
                continue
            k = norm_alias(a)
            if k in seen_alias and seen_alias[k] != code:
                problems.error(w, '별칭 "%s" 가 모델 %s 와 %s 에 함께 있습니다 [duplicate-alias]' % (a, seen_alias[k], code),
                               '한 별칭은 한 모델에만 둘 수 있습니다')
            seen_alias[k] = code
        good.append(m)
    return Models(good)
