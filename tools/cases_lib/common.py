"""Shared helpers: repository paths, JSON output, the model registry and the Problems collector."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
CASES = ROOT / 'cases'
SET_ID_RE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.-]{0,39}$')   # same rule as app.js / gc.js ensureSet()
PATIENT_RE = r'P\d{3,4}'


class Problems:
    """Collects human-readable errors and warnings (Korean first, English code in brackets) instead of stopping at the first one."""

    def __init__(self):
        self.errors, self.warnings = [], []

    def error(self, where, msg, hint=''):
        self.errors.append(self._fmt(where, msg, hint))

    def warn(self, where, msg, hint=''):
        self.warnings.append(self._fmt(where, msg, hint))

    @staticmethod
    def _fmt(where, msg, hint):
        s = (str(where) + ': ' if where else '') + msg
        return s + ('\n      → ' + hint if hint else '')

    def ok(self):
        return not self.errors

    def report(self, title=''):
        out = []
        if title:
            out.append(title)
        for e in self.errors:
            out.append('  ✗ 오류 ' + e)
        for w in self.warnings:
            out.append('  △ 확인 ' + w)
        if not self.errors and not self.warnings:
            out.append('  ✓ 문제 없음 (no problems)')
        return '\n'.join(out)


def rel(path):
    """Path relative to the repository root (for messages)."""
    try:
        return str(pathlib.Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def load_json(path, problems=None):
    try:
        return json.loads(pathlib.Path(path).read_text(encoding='utf-8'))
    except FileNotFoundError:
        if problems is not None:
            problems.error(rel(path), '파일이 없습니다 [missing-file]')
            return None
        raise
    except json.JSONDecodeError as e:
        if problems is not None:
            problems.error(rel(path) + ':%d' % e.lineno, 'JSON 형식 오류: %s [bad-json]' % e.msg,
                           '쉼표·따옴표·괄호를 확인하세요 (check commas, quotes and brackets)')
            return None
        raise


def dumps_pretty(obj):
    """The JSON layout of the committed data files (indent=1, non-ASCII kept)."""
    return json.dumps(obj, ensure_ascii=False, indent=1)


def window_js(var, obj, generator='tools/build_cases.py'):
    return '/* AUTO-GENERATED by %s — do not edit by hand. */\nwindow.%s = %s;\n' % (generator, var, dumps_pretty(obj))


def read_window_js(path, var):
    """Parse a generated `window.VAR = {...};` file back into Python (None if missing)."""
    p = pathlib.Path(path)
    if not p.exists():
        return None
    src = p.read_text(encoding='utf-8')
    marker = 'window.%s = ' % var
    body = src[src.index(marker) + len(marker):].strip()
    if body.endswith(';'):
        body = body[:-1]
    return json.loads(body)


